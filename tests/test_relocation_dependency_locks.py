import tempfile
from pathlib import Path
import unittest
from drive_manager.relocations import declared_dependency_lock

class DependencyLockTests(unittest.TestCase):
    def setUp(self):
        self.temp=tempfile.TemporaryDirectory();self.addCleanup(self.temp.cleanup)
        self.root=Path(self.temp.name);(self.root/'locks').mkdir()
        (self.root/'pyproject.toml').write_text('[tool.hatch.envs.default]\nlock-filename = "locks/{env_name}.lock"\n')
        (self.root/'locks/default.lock').write_text('#\n# This file is autogenerated by hatch-pip-compile with Python 3.10\n#\ntyper==1.0\n')
    def test_declared_hatch_dependency_file_is_recognized(self):
        self.assertTrue(declared_dependency_lock(self.root,'locks/default.lock'))
    def test_git_and_unknown_lock_paths_are_never_exempted(self):
        for path in ['.git/index.lock','index.lock','locks/nested/index.lock','../locks/default.lock']:
            self.assertFalse(declared_dependency_lock(self.root,path))
    def test_header_alone_does_not_authorize(self):
        (self.root/'pyproject.toml').write_text('[project]\nname="example"\n')
        self.assertFalse(declared_dependency_lock(self.root,'locks/default.lock'))
    def test_declaration_alone_does_not_authorize(self):
        (self.root/'locks/default.lock').write_text('active process lock')
        self.assertFalse(declared_dependency_lock(self.root,'locks/default.lock'))
    def test_symlinked_lock_is_rejected(self):
        (self.root/'locks/alias.lock').symlink_to('default.lock')
        self.assertFalse(declared_dependency_lock(self.root,'locks/alias.lock'))
    def test_invalid_configuration_is_rejected(self):
        (self.root/'pyproject.toml').write_text('invalid toml = [')
        self.assertFalse(declared_dependency_lock(self.root,'locks/default.lock'))
