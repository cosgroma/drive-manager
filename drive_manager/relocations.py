def automatic_collection(source):
    """Recognized historical collections, excluding repositories inside a checkout."""
    source=Path(source)
    root=next((p for p in source.parents if p.name=='repos'),None)
    allowed={(),('apps',),('atc',),('docs',),('jhu',),('libs',),('utils',),('opt',),
             ('libs','python'),('libs','python','modules'),('libs','sdr'),
             ('sergeant','docs'),('sergeant','docs','presentations'),
             ('sergeant','docs','systems_engineering'),('sergeant','docs','systems_engineering','architecture'),
             ('sergeant','docs','systems_engineering','analysis')}
    if root is None or source.parent.relative_to(root).parts not in allowed:
        raise ValueError('Automatic relocation requires a recognized historical repository collection')
    directory=source.parent
    while True:
        if os.path.lexists(directory/'.git') or ((directory/'HEAD').exists() and (directory/'objects').is_dir()):
            raise ValueError('A repository collection inside another repository needs coordinated review')
        if directory==root:break
        directory=directory.parent
    return root


def declared_dependency_lock(source, relative):
    """Recognize Hatch's declared dependency files, never Git's operational locks."""
    path=Path(relative)
    if len(path.parts)!=2 or path.parts[0]!='locks' or not path.name.endswith('.lock'):
        return False
    config=Path(source)/'pyproject.toml'
    try:
        if config.is_symlink() or config.stat().st_size>1024*1024:return False
        data=tomllib.loads(config.read_text())
        envs=data['tool']['hatch']['envs']
        if not any(isinstance(env,dict) and env.get('lock-filename')=='locks/{env_name}.lock' for env in envs.values()):
            return False
        lock=Path(source)/path
        if lock.is_symlink():return False
        with lock.open('rb') as stream:header=stream.read(512)
        return header.startswith(b'#\n# This file is autogenerated by hatch-pip-compile with Python ')
    except (OSError,ValueError,KeyError,TypeError):
        return False


def load_manifest(store, ident):
    with store.db() as db:
        row=db.execute('SELECT a.*,j.status FROM workspace_manifests a JOIN jobs j ON j.id=a.job_id WHERE a.job_id=?',(ident,)).fetchone()
    if row is None or row['status']!='completed' or not row['result']:
        raise ValueError('A completed full-tree manifest is required')
    result=json.loads(row['result'])
    path=store.state/'workspace-manifests'/ident/'manifest.sqlite3'
    sha=hashlib.sha256()
    with sqlite3.connect('file:'+str(path)+'?mode=ro',uri=True) as db:
        for rel,native,sig,digest in db.execute('SELECT relative,native,signature,sha256 FROM entries ORDER BY relative'):
            metadata=json.loads(native)
            if metadata['kind'] not in ('dir','file'):
                raise ValueError('Links and special entries need a separate archival plan')
            if metadata['kind']=='file' and rel.endswith('.lock') and not declared_dependency_lock(result['source'],rel):raise ValueError('Lock file present; close active tools and build a fresh manifest')
            if metadata['kind']=='file' and not digest:raise ValueError('Unhashed file in relocation manifest')
            sha.update(manifests.canonical(dict(relative=rel,native=metadata,signature=json.loads(sig) if sig else None,sha256=digest)).encode()+b'\n')
    if sha.hexdigest()!=result['sha256']:raise ValueError('Manifest database does not match its verification receipt')
    return result,path


def dependency_gate(source, automatic=False):
    """A native move retains external absolute paths; parent-relative dependencies are gated."""
    source=Path(source)
    bare=git(source,'rev-parse','--is-bare-repository',timeout=30).strip()=='true'
    gitdir=Path(git(source,'rev-parse','--absolute-git-dir',timeout=30).strip())
    common=Path(git(source,'rev-parse','--path-format=absolute','--git-common-dir',timeout=30).strip())
    expected=source if bare else source/'.git'
    if gitdir!=expected or common!=expected:raise ValueError('Linked worktrees or external Git directories need a separate relocation plan')
    locations=[line[9:] for line in git(source,'worktree','list','--porcelain',timeout=30).splitlines() if line.startswith('worktree ')]
    if locations!=[str(source)]:raise ValueError('Additional registered worktrees require coordinated relocation')
    if (common/'objects/info/alternates').exists():raise ValueError('External object alternates require dependency review')
    # Local configuration only: do not copy or print credential-bearing global configuration.
    config=git(source,'config','--local','--null','--list',timeout=30)
    values={};pairs=[]
    for line in config.split('\0'):
        if not line:continue
        key,_,value=line.partition('\n');values[key.lower()]=value;pairs.append((key.lower(),value))
    dangerous=('core.worktree','core.hookspath','core.fsmonitor','core.sshcommand','lfs.storage','include.path','includeif.')
    if any(any(key==p or (p.endswith('.') and key.startswith(p)) for p in dangerous) for key in values):
        raise ValueError('Configured path dependencies need a separate relocation plan')
    for key,value in pairs:
        if key.startswith('remote.') and key.endswith(('.url','.pushurl')):
            stable=value.startswith(('/','~/','\\\\')) or ':' in value
            if not stable:raise ValueError('Parent-relative remote URLs require a separate relocation plan')
    hooks=common/'hooks'
    if hooks.exists() and any(p.is_file() and not p.name.endswith('.sample') for p in hooks.iterdir()):
        raise ValueError('Active Git hooks require dependency review before relocation')
    if automatic:
        safe={'core.repositoryformatversion','core.filemode','core.bare','core.sharedrepository','core.logallrefupdates','core.ignorecase','core.symlinks','core.precomposeunicode'}
        if not bare or source.suffix!='.git' or any(key not in safe for key in values):
            raise ValueError('Automatic relocation is restricted to simple, self-contained bare archives')
        automatic_collection(source)
    return dict(bare=bare,git_dir=str(gitdir),common_dir=str(common),registered_worktrees=locations,
                external_object_alternates=False,active_hooks=False,local_config_keys=sorted(values))


def verify_tree(store, manifest, base, check=lambda:None, after_move=False):
    """Full payload/native metadata verification, including membership on both sides of reads."""
    result,path=load_manifest(store,manifest)
    base=Path(base)
    directory=store.state/'relocation-checks';directory.mkdir(parents=True,exist_ok=True)
    token=uuid.uuid4().hex;initial=directory/(token+'-initial.jsonl');final=directory/(token+'-final.jsonl')
    db=sqlite3.connect('file:'+str(path)+'?mode=ro',uri=True)
    try:
        manifests.enumerate_tree(base,initial,check)
        seen=0
        for rel,metadata in manifests.entries(initial):
            check();row=db.execute('SELECT native,signature,sha256 FROM entries WHERE relative=?',(rel,)).fetchone()
            if row is None or manifests.canonical(metadata)!=row[0]:
                raise ValueError('Tree membership or native metadata differs from the approved manifest: '+rel)
            expected=json.loads(row[1]);current=manifests.file_signature(base/rel)
            keys=('size','mtime_ns','mode','uid','gid','nlink') if after_move else tuple(k for k in expected if not (rel=='.' and k=='ctime_ns'))
            if any(current[k]!=expected[k] for k in keys):raise ValueError('File identity or metadata changed: '+rel)
            if metadata['kind']=='file' and manifests.checked_hash(base/rel,current,check)!=row[2]:
                raise ValueError('File payload differs from the approved manifest: '+rel)
            seen+=1
        if seen!=result['entries']:raise ValueError('Manifest entries are missing from the source tree')
        manifests.enumerate_tree(base,final,check)
        count=0
        for rel,metadata in manifests.entries(final):
            check();row=db.execute('SELECT native FROM entries WHERE relative=?',(rel,)).fetchone()
            if row is None or row[0]!=manifests.canonical(metadata):raise ValueError('Tree changed during relocation verification: '+rel)
            count+=1
        if count!=seen:raise ValueError('Tree membership changed during relocation verification')
        return result
    finally:
        db.close();initial.unlink(missing_ok=True);final.unlink(missing_ok=True)


def remove_alias(source,destination):
    if not is_junction(source,destination):raise ValueError('Legacy path is not the expected compatibility link; nothing removed')
    if str(source).startswith('/mnt/'):
        powershell('[IO.Directory]::Delete($x.source)',{'source':windows_path(source)})
    else:source.unlink()


def propose(store, manifest, automatic=False, archive_root=None, reason='Archive this historical working tree intact and retain its old path as a compatibility junction'):
    result,_=load_manifest(store,manifest)
    source,root=store.safe_path(result['source'])
    if source==root or 'archive' in source.relative_to(root).parts:raise ValueError('Choose an original repository below a drive root')
    dependencies=dependency_gate(source,automatic)
    ident=uuid.uuid4().hex
    target=Path(archive_root) if archive_root else root/'archive/workspaces'
    store.safe_path(str(target),True)
    destination=target/root.name/source.relative_to(root)/'tree'/(time.strftime('%Y%m%dT%H%M%SZ',time.gmtime())+'-'+ident[:12])
    store.safe_path(str(destination),True)
    with store.db() as db:
        old=db.execute("SELECT id FROM candidates WHERE kind='workspace_archive' AND source=? AND status IN ('review','queued')",(str(source),)).fetchone()
        if old:return old[0]
        snapshot={'manifest':manifest,'manifest_sha256':result['sha256'],'root':manifests.file_signature(source),'dependencies':dependencies,'automatic_bare':automatic}
        db.execute("INSERT INTO candidates(id,kind,source,destination,snapshot,size,reason,confidence,created,updated) VALUES(?,'workspace_archive',?,?,?,?,?,?,?,?)",
                   (ident,str(source),str(destination),json.dumps(snapshot),result['bytes'],reason,'goal' if automatic else 'review',time.time(),time.time()))
    store.event('Archival relocation proposed, with compatibility path and zero space reclamation: '+str(source)+' → '+str(destination))
    if automatic:authorize_goal(store,ident)
    return ident



def refresh_review(store, ident, manifest, previous_manifest):
    """Replace only an unapproved archival baseline; retain the user's decision."""
    with store.db() as db:
        row=db.execute('SELECT * FROM candidates WHERE id=?',(ident,)).fetchone()
    if row is None or row['kind']!='workspace_archive' or row['status']!='review' or row['job_id']:
        raise ValueError('Only an unapproved archival proposal can be refreshed')
    old=json.loads(row['snapshot'])
    if old.get('automatic_bare') or row['confidence']!='review':
        raise ValueError('Only checkbox review proposals can be refreshed')
    if old.get('manifest')!=previous_manifest or manifest==previous_manifest:
        raise ValueError('Refresh requires the expected old manifest and a new manifest')
    result,manifest_path=load_manifest(store,manifest)
    if result['source']!=row['source']:
        raise ValueError('Fresh manifest must cover the same source')
    source,root=store.safe_path(row['source'])
    destination,other=store.safe_path(row['destination'],True)
    if root!=other or source==destination or source in destination.parents or destination in source.parents or os.path.lexists(destination):
        raise ValueError('Retained archival destination is no longer available')
    with sqlite3.connect('file:'+str(manifest_path)+'?mode=ro',uri=True) as db:
        sealed=db.execute("SELECT signature FROM entries WHERE relative='.'").fetchone()
    current=manifests.file_signature(source)
    if sealed is None or json.loads(sealed[0])!=current:
        raise ValueError('Source root changed since the fresh inventory')
    dependencies=dependency_gate(source)
    snapshot=dict(manifest=manifest,manifest_sha256=result['sha256'],root=current,
                  dependencies=dependencies,automatic_bare=False)
    with store.db() as db:
        db.execute('BEGIN IMMEDIATE')
        fresh=db.execute('SELECT status,snapshot,job_id FROM candidates WHERE id=?',(ident,)).fetchone()
        if not fresh or fresh['status']!='review' or fresh['snapshot']!=row['snapshot'] or fresh['job_id']:
            raise ValueError('Proposal changed during refresh; no baseline replaced')
        db.execute('UPDATE candidates SET snapshot=?,size=?,updated=? WHERE id=?',
                   (json.dumps(snapshot),result['bytes'],time.time(),ident))
        event=dict(candidate=ident,previous_manifest=previous_manifest,manifest=manifest,
                   previous_manifest_sha256=old.get('manifest_sha256'),manifest_sha256=result['sha256'])
        db.execute('INSERT INTO events(at,job_id,message) VALUES(?,NULL,?)',
                   (time.time(),'Archival review baseline refreshed; checkbox approval still required: '+json.dumps(event,sort_keys=True)))
    return ident


def validate(store,candidate):
    snap=json.loads(candidate['snapshot']);result,_=load_manifest(store,snap['manifest'])
    if result['sha256']!=snap['manifest_sha256']:raise ValueError('Reviewed manifest changed')
    src,root=store.safe_path(candidate['source']);dst,other=store.safe_path(candidate['destination'],True)
    if root!=other or src==dst or src in dst.parents or dst in src.parents or os.path.lexists(dst):
        raise ValueError('Relocation requires separate paths on one drive and an absent destination')
    if manifests.file_signature(src)!=snap['root']:raise ValueError('Source root changed since proposal; prepare a fresh review')
    dependency_gate(src,snap['automatic_bare'])
    return snap


def authorize_goal(store,ident):
    with store.db() as db:
        row=db.execute('SELECT * FROM candidates WHERE id=?',(ident,)).fetchone()
    snap=validate(store,row)
    if not snap['automatic_bare'] or row['confidence']!='goal':raise ValueError('Working-tree archival requires checkbox approval')
    # Explicit goal authorization, never represented as a user checkbox action.
    with store.db() as db:
        db.execute('BEGIN IMMEDIATE')
        fresh=db.execute('SELECT status,snapshot FROM candidates WHERE id=?',(ident,)).fetchone()
        if fresh['status']!='review' or fresh['snapshot']!=row['snapshot']:raise ValueError('Archival proposal is no longer pending')
        job=uuid.uuid4().hex
        db.execute("INSERT INTO jobs(id,kind,path,status,payload,created,updated) VALUES(?,'transfer',?,'pending',?,?,?)",(job,row['source'],json.dumps({'candidate':ident}),time.time(),time.time()))
        db.execute("UPDATE candidates SET status='queued',job_id=?,updated=? WHERE id=?",(job,time.time(),ident))
        db.execute('INSERT INTO events(at,job_id,message) VALUES(?,?,?)',(time.time(),job,'Goal authorized high-confidence bare archival relocation: '+row['source']+' → '+row['destination']))
    return job


def catalog(store):
    with store.db() as db:
        rows=db.execute("SELECT c.*,j.status job_status,j.message FROM candidates c LEFT JOIN jobs j ON j.id=c.job_id WHERE c.kind IN ('workspace_archive','workspace_restore','workspace_restore_review') ORDER BY c.created DESC").fetchall()
    output=[]
    for row in rows:
        item=dict(row)
        original=json.loads(row['snapshot'])['original'] if row['kind']=='workspace_restore_review' else row['job_id'] or row['id']
        receipt=store.state/'workspace-relocations'/(original+'.json')
        item['receipt']=json.loads(receipt.read_text()) if receipt.exists() else None
        output.append(item)
    return output


def relocation_receipt(store,original):
    if not isinstance(original,str) or len(original)!=32 or any(c not in '0123456789abcdef' for c in original):
        raise ValueError('Unknown archival relocation')
    path=store.state/'workspace-relocations'/(original+'.json')
    if not path.is_file():raise ValueError('Unknown archival relocation')
    raw=path.read_bytes()
    return path,json.loads(raw),hashlib.sha256(raw).hexdigest()


def validate_reviewed_restore(store,candidate,*,allow_missing_alias=False):
    snap=json.loads(candidate['snapshot']);_,receipt,receipt_sha=relocation_receipt(store,snap['original'])
    src,dst=Path(receipt['source']),Path(receipt['destination'])
    if receipt['phase']!='archived' or receipt_sha!=snap['receipt_sha256']:
        raise ValueError('Relocation recovery state changed; prepare a fresh restoration review')
    if candidate['source']!=str(dst) or candidate['destination']!=str(src):
        raise ValueError('Restoration paths differ from the original archival relocation')
    _,drive=store.safe_path(str(dst));_,other=store.safe_path(str(src.parent))
    alias_ok=(allow_missing_alias and not os.path.lexists(src)) or is_junction(src,dst)
    if drive!=other or not alias_ok:raise ValueError('Original path is not the expected compatibility junction')
    result,_=load_manifest(store,snap['manifest'])
    if result['source']!=str(dst) or result['sha256']!=snap['manifest_sha256']:
        raise ValueError('Restoration requires a complete manifest of this exact archived tree')
    if manifests.file_signature(dst)!=snap['root']:raise ValueError('Archive root changed since review; prepare a fresh baseline')
    dependency_gate(dst)
    with store.db() as db:
        other_job=db.execute("SELECT id FROM jobs WHERE kind='workspace_restore' AND path=? AND status IN ('pending','running','paused','blocked','failed')",(str(dst),)).fetchone()
        other_review=db.execute("SELECT id FROM candidates WHERE kind='workspace_restore_review' AND source=? AND status='queued' AND id!=?",(str(dst),candidate['id'])).fetchone()
    if other_job or other_review:raise ValueError('Cancel or finish the existing restoration job before reviewing a fresh baseline')
    return snap


def propose_reviewed_restore(store,original,manifest):
    _,receipt,receipt_sha=relocation_receipt(store,original)
    result,_=load_manifest(store,manifest)
    candidate={'id':uuid.uuid4().hex,'source':receipt['destination'],'destination':receipt['source'],
               'snapshot':json.dumps({'original':original,'receipt_sha256':receipt_sha,'manifest':manifest,
                                     'manifest_sha256':result['sha256'],'root':manifests.file_signature(Path(receipt['destination']))})}
    validate_reviewed_restore(store,candidate)
    with store.db() as db:
        db.execute('BEGIN IMMEDIATE')
        for row in db.execute("SELECT id,status,snapshot FROM candidates WHERE kind='workspace_restore_review' AND source=? ORDER BY created DESC",(candidate['source'],)):
            old=json.loads(row['snapshot'])
            if row['status'] in ('review','queued'):
                if old['manifest']==manifest:return row['id']
                raise ValueError('Review or dismiss the existing restoration proposal before replacing its baseline')
            if row['status']=='rejected' and old['manifest']==manifest:raise ValueError('This restoration baseline was rejected; decision retained')
        reason=('Restore the complete current archived tree to its original physical location using the fresh manifest '+manifest+
                '. Preserve all '+str(result['files'])+' files, newer edits and Git refs. The original archive manifest remains in the audit trail. Zero space reclaimed.')
        db.execute("INSERT INTO candidates(id,kind,source,destination,snapshot,size,reason,confidence,created,updated) VALUES(?,'workspace_restore_review',?,?,?,?,?,'review',?,?)",
                   (candidate['id'],candidate['source'],candidate['destination'],candidate['snapshot'],result['bytes'],reason,time.time(),time.time()))
    store.event('Fresh-baseline restoration prepared for checkbox review; no move approved: '+candidate['source'])
    return candidate['id']


def run_reviewed_restore(store,job,candidate):
    if candidate['kind']!='workspace_restore_review' or candidate['job_id']!=job['id'] or candidate['status'] not in ('queued','completed'):
        raise ValueError('Restoration is not bound to this approved job')
    snap=json.loads(candidate['snapshot']);_,receipt,_=relocation_receipt(store,snap['original'])
    if receipt['source']!=candidate['destination'] or receipt['destination']!=candidate['source'] or receipt['job']!=snap['original']:
        raise ValueError('Restoration recovery paths no longer match the approved operation')
    result,_=load_manifest(store,snap['manifest'])
    if result['source']!=candidate['source'] or result['sha256']!=snap['manifest_sha256']:
        raise ValueError('Approved restoration manifest changed')
    proof=store.state/'workspace-restorations'/(job['id']+'.json')
    binding=dict(job=job['id'],candidate=candidate['id'],original=snap['original'],manifest=snap['manifest'],
                 manifest_sha256=snap['manifest_sha256'],original_receipt_sha256=snap['receipt_sha256'],
                 source=candidate['source'],destination=candidate['destination'])
    authorized=proof.exists() and json.loads(proof.read_text())==binding
    if Path(candidate['source']).exists():
        # A crash may interrupt alias removal before the native rename. Rebuild
        # only this job's missing alias, after checking its entire approved tree.
        if not os.path.lexists(candidate['destination']) and authorized and receipt['phase']=='archived':
            validate_reviewed_restore(store,candidate,allow_missing_alias=True)
            verify_tree(store,snap['manifest'],candidate['source'],lambda:store.check(job['id']),after_move=True)
            create_junction(Path(candidate['destination']),Path(candidate['source']))
        validate_reviewed_restore(store,candidate)
        # Durable authorization survives a crash after publication at the old path.
        store.write_receipt(proof,binding)
    else:
        # Publication can finish just before its receipt update becomes durable.
        # run_restore still verifies the complete physical original below.
        if not authorized or receipt['phase'] not in ('archived','restore_published','restored'):
            raise ValueError('Reviewed restoration recovery proof is missing; preserve current folder locations')
    proxy={**job,'payload':json.dumps({'original':snap['original']})}
    run_restore(store,proxy,manifest=snap['manifest'])
    with store.db() as db:db.execute("UPDATE candidates SET status='completed',updated=? WHERE id=?",(time.time(),candidate['id']))


def _rollback(store,receipt,path, verify=True):
    src,dst=Path(receipt['source']),Path(receipt['destination'])
    if os.path.lexists(src):
        remove_alias(src,dst)
    if os.path.lexists(src):raise ValueError('Original location is occupied; archived files retained')
    try:publish_directory(dst,src)
    except BaseException:
        if not os.path.lexists(src) and dst.exists():create_junction(src,dst)
        raise
    if verify:verify_tree(store,receipt['manifest'],src,after_move=True)
    receipt['phase']='rolled_back' if verify else 'restore_published';receipt['rolled_back_at']=time.time();store.write_receipt(path,receipt)
    store.event('Archival move rolled back; complete original tree is back at '+str(src),receipt['job'])


def run(store,job,candidate):
    src,dst=Path(candidate['source']),Path(candidate['destination'])
    snap=json.loads(candidate['snapshot']);check=lambda:store.check(job['id'])
    path=store.state/'workspace-relocations'/(job['id']+'.json')
    receipt=json.loads(path.read_text()) if path.exists() else None
    if receipt and (receipt['source']!=str(src) or receipt['destination']!=str(dst) or receipt['manifest_sha256']!=snap['manifest_sha256']):
        raise ValueError('Relocation recovery receipt differs from its approved proposal')
    moved=dst.exists() and receipt is not None and receipt['phase'] in ('preverified','moved','linked','archived')
    if moved and not os.path.lexists(src):
        verify_tree(store,snap['manifest'],dst,check,after_move=True)
    if not moved:
        if os.path.lexists(dst):raise ValueError('Destination exists; nothing overwritten')
        store.safe_path(str(src));store.safe_path(str(dst),True)
        dependency_gate(src,snap['automatic_bare'])
        store.progress(job['id'],0,0,'Revalidating every payload and native metadata before archival move')
        result=verify_tree(store,snap['manifest'],src,check)
        check();dst.parent.mkdir(parents=True,exist_ok=True)
        receipt={'job':job['id'],'candidate':candidate['id'],'source':str(src),'destination':str(dst),'manifest':snap['manifest'],
                 'manifest_sha256':snap['manifest_sha256'],'phase':'preverified','space_reclaimed':0,'source_data_retained':True,
                 'compatibility_path':str(src),'at':time.time()}
        store.write_receipt(path,receipt)
    try:
        if not moved:
            publish_directory(src,dst);moved=True
            receipt['phase']='moved';store.write_receipt(path,receipt)
        if not os.path.lexists(src):create_junction(src,dst)
        if not is_junction(src,dst):raise ValueError('Original path is occupied or has an unexpected junction target')
        receipt['phase']='linked';store.write_receipt(path,receipt)
        store.progress(job['id'],0,0,'Verifying archived data, permissions and legacy-path access')
        result=verify_tree(store,snap['manifest'],dst,check,after_move=True)
        # Check all file payloads through the compatibility path as well.
        from .core import digest
        _,database=load_manifest(store,snap['manifest'])
        with sqlite3.connect(database) as db:
            for rel,sha in db.execute('SELECT relative,sha256 FROM entries WHERE sha256 IS NOT NULL'):
                if digest(src/rel,check)!=sha:raise ValueError('Legacy-path payload read failed: '+rel)
        legacy_streams=manifests.verify_named_streams(src,database,check)
        from .workspaces import refs
        if refs(src,check)!=refs(dst,check):raise ValueError('Git refs differ through the compatibility path')
        receipt.update(phase='archived',verified_at=time.time(),files=result['files'],bytes=result['bytes'],
                       payloads_verified=True,native_metadata_verified=True,legacy_payload_reads_verified=True,
                       legacy_named_streams_verified=legacy_streams)
        store.write_receipt(path,receipt)
        store.index_transfer(src,dst,job['id'],remove_source=True,directory=True)
        with store.db() as db:db.execute("UPDATE candidates SET status='completed',updated=? WHERE id=?",(time.time(),candidate['id']))
        store.progress(job['id'],result['files'],result['bytes'],'Archived intact; legacy path verified; zero space reclaimed')
        store.event('Verified archival relocation complete: '+str(src)+' → '+str(dst),job['id'])
    except BaseException as original:
        if not moved and not os.path.lexists(src) and dst.exists():
            expected=snap['root'];actual=manifests.file_signature(dst)
            moved=(actual['device'],actual['inode'])==(expected['device'],expected['inode'])
        if not moved:raise
        try:_rollback(store,receipt,path)
        except BaseException as error:
            store.event('Rollback needs attention; source and archive paths retained in receipt: '+str(error),job['id'])
            raise ValueError('Verification failed and automatic rollback needs attention; folder locations recorded in receipt: '+str(error)) from original
        with store.db() as db:db.execute("UPDATE candidates SET status='queued',updated=? WHERE id=?",(time.time(),candidate['id']))
        raise


def enqueue_restore(store, original):
    path=store.state/'workspace-relocations'/(original+'.json')
    if len(original)!=32 or any(c not in '0123456789abcdef' for c in original) or not path.exists():
        raise ValueError('Unknown archival relocation')
    receipt=json.loads(path.read_text())
    if receipt['phase']!='archived':raise ValueError('Only a verified archival relocation can be restored')
    src,dst=Path(receipt['source']),Path(receipt['destination'])
    store.safe_path(str(src.parent));store.safe_path(str(dst))
    if not is_junction(src,dst):raise ValueError('Legacy path is no longer the expected compatibility junction')
    with store.db() as db:
        reviewed=db.execute("SELECT status,job_id FROM candidates WHERE kind='workspace_restore_review' AND source=? AND status IN ('review','queued')",(str(dst),)).fetchone()
        if reviewed:
            if reviewed['status']=='queued':return reviewed['job_id']
            raise ValueError('Review or dismiss the pending fresh-baseline restoration proposal first')
        old=db.execute("SELECT id FROM jobs WHERE kind='workspace_restore' AND path=? AND status IN ('pending','running','paused','blocked','failed')",(str(dst),)).fetchone()
    if old:return old[0]
    ident=store.enqueue('workspace_restore',str(dst),{'original':original})
    store.event('User requested restoration of the original folder location: '+str(src),ident)
    return ident


def run_restore(store,job,manifest=None):
    original=json.loads(job['payload'])['original']
    if len(original)!=32 or any(c not in '0123456789abcdef' for c in original):raise ValueError('Invalid relocation recovery identifier')
    path=store.state/'workspace-relocations'/(original+'.json');receipt=json.loads(path.read_text())
    baseline=manifest or receipt['manifest']
    src,dst=Path(receipt['source']),Path(receipt['destination']);check=lambda:store.check(job['id'])
    store.safe_path(str(src.parent));store.safe_path(str(dst.parent))
    store.progress(job['id'],0,0,'Verifying archived data before restoring the original physical folder')
    if dst.exists():
        verify_tree(store,baseline,dst,check,after_move=True)
        check();_rollback(store,receipt,path,verify=False)
    else:
        # Reconcile a crash after moving the complete tree back, before recording it.
        store.safe_path(str(src))
    result=verify_tree(store,baseline,src,check,after_move=True)
    receipt.update(phase='restored',restored_at=time.time(),restore_job=job['id'],restore_manifest=baseline,
                   restore_manifest_sha256=result['sha256'])
    store.write_receipt(path,receipt)
    with store.db() as db:db.execute("UPDATE candidates SET status='restored',updated=? WHERE id=?",(time.time(),receipt['candidate']))
    store.index_transfer(dst,src,job['id'],remove_source=True,directory=True)
    store.progress(job['id'],result['files'],result['bytes'],'Original physical folder restored and fully verified')
    store.event('Original folder location restored: '+str(src),job['id'])
